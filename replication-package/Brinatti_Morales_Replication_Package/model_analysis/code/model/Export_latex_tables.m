%% =============================================================
%  Sec 6.1 dollar gains — monetary conversion to 2019 USD PPP
%  Reuses the three percentages already computed for sec61_aggregates
%  (ne_p, fo_p, ti_p) and scales them by OECD constants for Germany
%  2019 to recover dollar-amount gains.
%
%  Four OECD constants drive the dollar-amount conversion, hardcoded
%  here for reproducibility:
%
%  Constant                                     | Value
%  ---------------------------------------------+---------------
%  per-worker wage (constant 2019 USD PPP)      |   46,838
%  GDP (mn, current 2019 USD PPP)               |  4,928,323.5
%  Dependent employees (thousand)               |     41,145
%  Markup (aggregate, model output)             |      3.0833
%
%  Unit note: OECD's AV_AN_WAGE is published as REAL average annual wages
%  (constant prices); EO 2020 Table N is labelled "Real average annual
%  wages ... 2019 USD PPP".
%  OECD's National-Accounts GDP series above is published in current
%  2019 USD PPP for the year 2019. For 2019 itself, "constant 2019" and
%  "current 2019" coincide (the deflator at the base year is 1).
%
%  Per-worker wage derivation: OECD's AV_AN_WAGE is per-FTE; the model maps
%  to a per-worker concept (each LIAB worker is one person, not one FTE), so
%  the per-FTE value is divided by the FT-hours / all-employee-hours ratio:
%
%    Step                                                       | Value
%    -----------------------------------------------------------+--------
%    OECD EO 2020 Table N (per-FTE, real, constant 2019 USD PPP)| 53,638
%    ÷ FT-hours / all-hours ratio (39.43 / 34.432 = 1.1452)     | ÷ 1.1452
%    = per-worker average wage (real, constant 2019 USD PPP)    | = 46,838
%  ========================================================================

% Fractional changes (ne_p, fo_p, ti_p are already in percent)

earn_p_ch        = ne_p / 100;
prof_p_ch        = fo_p / 100;
total_income_ch  = ti_p / 100;

% Initial-equilibrium employment counts: needed to derive the immigrant
% share of the labor force. Loaded directly from the heterog-open .mat
% workspace since the h_open table only stores percentage changes.

W61 = load(fullfile(pkg_root, ...
        'code/model/heterogeneous/Results_counterfactuals/Counterfactual_heterogeneous_open.mat'), ...
        'main_aggregates_0');
Limm_count_0    = W61.main_aggregates_0(10);
Limm_nt_count_0 = W61.main_aggregates_0(11);
Ld_count_0      = W61.main_aggregates_0(13);
Ld_nt_count_0   = W61.main_aggregates_0(14);

AVG_WAGE_PPP_USD       = 46838;        % OECD per-worker wage DE 2019, 2019 USD PPP (see derivation above)
LF_TOTAL_THOUSAND      = 41145;        % OECD National Accounts dependent employees (SAL), DE 2019
GDP_USDPPP_MN          = 4928323.5;    % OECD GDP DE 2019, current 2019 USD PPP (millions)
MARKUP_AGGREGATE       = 3.1 ;         % Model aggregate markup

% Immigrant share from the model's initial-equilibrium employment counts
imm_total_count = Limm_count_0 + Limm_nt_count_0;
nat_total_count = Ld_count_0   + Ld_nt_count_0;
immigrant_share = imm_total_count / (imm_total_count + nat_total_count);

% Convert OECD inputs from thousand/million to absolute persons / dollars
LF_TOTAL          = LF_TOTAL_THOUSAND * 1e3;           % persons
NATIVE_LF         = LF_TOTAL * (1 - immigrant_share);  % persons
GDP_USDPPP        = GDP_USDPPP_MN * 1e6;               % dollars
PROFIT_INCOME_USD = GDP_USDPPP / MARKUP_AGGREGATE;     % aggregate profit income, dollars

% Dollar-amount conversion
native_gain_USD       = AVG_WAGE_PPP_USD * NATIVE_LF * earn_p_ch;
firm_owner_gain_USD   = PROFIT_INCOME_USD            * prof_p_ch;
total_income_gain_USD = native_gain_USD + firm_owner_gain_USD;

fid = fopen(fullfile(tables_out, 'sec61_dollar_gains.tex'), 'w');
fprintf(fid, '%% Auto-generated by Export_latex_tables.m\n');
fprintf(fid, '\\begin{tabular}{lcc}\n');
fprintf(fid, '\\toprule\n');
fprintf(fid, ' & Welfare change (\\%%) & USD (2019, PPP, billions) \\\\\n');
fprintf(fid, '\\midrule\n');
fprintf(fid, 'Native workers   & %.3f\\%% & \\$%.1f \\\\\n', earn_p_ch*100,       native_gain_USD/1e9);
fprintf(fid, 'Firm owners      & %.3f\\%% & \\$%.1f \\\\\n', prof_p_ch*100,       firm_owner_gain_USD/1e9);
fprintf(fid, 'Total income     & %.3f\\%% & \\$%.1f \\\\\n', total_income_ch*100, total_income_gain_USD/1e9);
fprintf(fid, '\\bottomrule\n');
fprintf(fid, '\\end{tabular}\n');
fclose(fid);
fprintf('Wrote %s\n', fullfile(tables_out, 'sec61_dollar_gains.tex'));

