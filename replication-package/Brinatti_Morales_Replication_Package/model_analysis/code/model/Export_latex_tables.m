% =============================================================
% Local function: snapshot_calibration
%
% Returns:
%   Mom_Model  - struct of simulated moments (used by tableC7.tex)
%   Mom_Data   - struct of targeted data moments (Mom_Data_draft in
%                Calibration_Res.m, Section 4)
%   PP_cal     - parameter struct with the calibrated values mapped in
%                (consumed by table1.tex)
% =============================================================

function [Mom_Model, Mom_Data, PP_cal] = snapshot_calibration(pkg_root)

    heterog_dir = fullfile(pkg_root, 'code', 'model', 'heterogeneous');
    orig_dir    = pwd;
    cleanup     = onCleanup(@() cd(orig_dir));

    cd(heterog_dir);
    addpath('Other_functions', 'Equations_equilibrium');

    PP = Setup_PP();

    % Start vector (matches Counterfactual_heterogeneous_open.m's x_0).
    Equil_0 = [0.324335125689298  0.00581557463337634 ...
               0.0112510772006113 0.161173107360179 ...
               360.337575599634   5559.82876523402 ...
               0.876877518299593  0.134468674352483 ...
               0.0131989032931402 189.138983348911];

    % InputVec layout must match the "Read the input vectors" block in
    % Calibration_Res.m.
    InputVec = [PP.taugx;        PP.sigma_psi;   PP.cov_psif;   PP.sigma_f; ...
                PP.beta_nt;      PP.beta;        PP.sigma_psi_nt; PP.cov_psif_nt; ...
                PP.sigma_f_nt;   PP.f_g;         PP.mu_psix;    PP.f_imm; ...
                PP.f_imm_nt;     PP.iota];

    % Calibration_Res declares its own `global Equil_0_last`.
    [~, PP_cal, ExtraDetails, ExitFlag] = Calibration_Res(PP, Equil_0, InputVec);

    if ExitFlag ~= 1
        error('snapshot_calibration: ExitFlag=%d (1 = success). Snapshot failed.', ExitFlag);
    end

    Mom_Model = ExtraDetails.Mom_Model;
    Mom_Data  = ExtraDetails.Mom_Data_draft;
end
