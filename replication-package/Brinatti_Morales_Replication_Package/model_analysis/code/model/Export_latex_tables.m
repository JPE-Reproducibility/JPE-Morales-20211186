% =============================================================
% Local function: build_h_open_from_mat
% Loads the raw equilibrium objects persisted by
% Counterfactual_heterogeneous_open.m and returns a 1-column table whose
% row names match the labels this script uses via ch(h_open, name).
% Stored values are percentage changes.
% =============================================================

function T = build_h_open_from_mat(mat_path)
    W = load(mat_path, 'x_sol_0', 'x_sol', 'main_aggregates_0', ...
                       'main_aggregates', 'PP');

    % --- Unpack the elements needed (indexing matches equilLoop outputs) ---
    wd_0 = 1;  wd = 1;
    wx_0      = W.x_sol_0(1);   wx      = W.x_sol(1);
    Pd_0      = W.x_sol_0(2);   Pd      = W.x_sol(2);
    wimm_0    = W.x_sol_0(4);   wimm    = W.x_sol(4);
    wd_nt_0   = W.x_sol_0(7);   wd_nt   = W.x_sol(7);
    wimm_nt_0 = W.x_sol_0(8);   wimm_nt = W.x_sol(8);
    Pd_nt_0   = W.x_sol_0(9);   Pd_nt   = W.x_sol(9);

    Ld_alt_0      = W.main_aggregates_0(5);    Ld_alt    = W.main_aggregates(5);
    I_alt_0       = W.main_aggregates_0(6);    I_alt     = W.main_aggregates(6);
    Ld_alt_nt_0   = W.main_aggregates_0(7);    Ld_alt_nt = W.main_aggregates(7);
    I_alt_nt_0    = W.main_aggregates_0(8);    I_alt_nt  = W.main_aggregates(8);
    Limm_count_0    = W.main_aggregates_0(10); Limm_count    = W.main_aggregates(10);
    Limm_nt_count_0 = W.main_aggregates_0(11); Limm_nt_count = W.main_aggregates(11);
    Ld_count_0      = W.main_aggregates_0(13); Ld_count      = W.main_aggregates(13);
    Ld_nt_count_0   = W.main_aggregates_0(14); Ld_nt_count   = W.main_aggregates(14);
    rev_t_0   = W.main_aggregates_0(16);       rev_t  = W.main_aggregates(16);
    rev_nt_0  = W.main_aggregates_0(17);       rev_nt = W.main_aggregates(17);

    alpha = W.PP.alpha;

    % --- Numeraire (ratio against export wage) ---
    norm_0 = wx_0;
    norm   = wx;

    % --- CES price index ---
    p_0 = ((Pd_0/(1-alpha))^(1-alpha) * (Pd_nt_0/alpha)^alpha) / norm_0;
    p   = ((Pd  /(1-alpha))^(1-alpha) * (Pd_nt  /alpha)^alpha) / norm;

    % --- Real native earnings (welfare measure for natives) ---
    earn_0 = ((Ld_alt_0*wd_0 + Ld_alt_nt_0*wd_nt_0) / (Ld_count_0 + Ld_nt_count_0)) / norm_0;
    earn   = ((Ld_alt  *wd   + Ld_alt_nt  *wd_nt  ) / (Ld_count   + Ld_nt_count  )) / norm;
    earn_p_ch = (earn/p) / (earn_0/p_0) - 1;

    % --- Real firm-owner welfare (profits / price index). PP_0.pid and
    % pid_nt are stored at positions 5 and 10 of x_sol. ---
    pid_0     = W.x_sol_0(5);   pid     = W.x_sol(5);
    pid_nt_0  = W.x_sol_0(10);  pid_nt  = W.x_sol(10);
    prof_0 = (pid_0 + pid_nt_0) / norm_0;
    prof   = (pid   + pid_nt  ) / norm;
    prof_p_ch = (prof/p) / (prof_0/p_0) - 1;

    % --- Real total income (revenues / price index) ---
    total_income_real_0 = ((rev_t_0 + rev_nt_0) / norm_0) / p_0;
    total_income_real   = ((rev_t   + rev_nt  ) / norm  ) / p;
    income_real_ch = total_income_real / total_income_real_0 - 1;

    % --- Sectoral employment (% changes; head-count and effective units) ---
    emp_T_ch          = ((Limm_count    + Ld_count   ) / (Limm_count_0    + Ld_count_0   )) - 1;
    emp_NT_ch         = ((Limm_nt_count + Ld_nt_count) / (Limm_nt_count_0 + Ld_nt_count_0)) - 1;
    emp_nat_T_ch      =  Ld_count    / Ld_count_0    - 1;
    emp_nat_NT_ch     =  Ld_nt_count / Ld_nt_count_0 - 1;
    emp_imm_T_ch      =  Limm_count    / Limm_count_0    - 1;
    emp_imm_NT_ch     =  Limm_nt_count / Limm_nt_count_0 - 1;
    emp_eff_T_ch      = ((I_alt    + Ld_alt   ) / (I_alt_0    + Ld_alt_0   )) - 1;
    emp_eff_NT_ch     = ((I_alt_nt + Ld_alt_nt) / (I_alt_nt_0 + Ld_alt_nt_0)) - 1;
    emp_eff_nat_T_ch  =  Ld_alt    / Ld_alt_0    - 1;
    emp_eff_nat_NT_ch =  Ld_alt_nt / Ld_alt_nt_0 - 1;
    emp_eff_imm_T_ch  =  I_alt    / I_alt_0    - 1;
    emp_eff_imm_NT_ch =  I_alt_nt / I_alt_nt_0 - 1;

    % --- Wages (labor units = earn_T/NT per native head; effective units
    % = w_T/NT and w_imm_T/NT per effective unit) ---
    earn_T_0 = ((Ld_alt_0*wd_0)/Ld_count_0)/norm_0;
    earn_T   = ((Ld_alt  *wd  )/Ld_count  )/norm;
    earn_NT_0 = ((Ld_alt_nt_0*wd_nt_0)/Ld_nt_count_0)/norm_0;
    earn_NT   = ((Ld_alt_nt  *wd_nt  )/Ld_nt_count  )/norm;
    earn_T_ch  = earn_T  / earn_T_0  - 1;
    earn_NT_ch = earn_NT / earn_NT_0 - 1;

    w_T_ch        = (wd     /norm) / (wd_0     /norm_0) - 1;
    w_NT_ch       = (wd_nt  /norm) / (wd_nt_0  /norm_0) - 1;
    w_imm_T_ch    = (wimm   /norm) / (wimm_0   /norm_0) - 1;
    w_imm_NT_ch   = (wimm_nt/norm) / (wimm_nt_0/norm_0) - 1;

    % Immigrant per-head earnings (labor units, using native wage rate × effective units)
    earn_T_imm_0  = ((I_alt_0   *wd_0  )/Limm_count_0   )/norm_0;
    earn_T_imm    = ((I_alt     *wd    )/Limm_count     )/norm;
    earn_NT_imm_0 = ((I_alt_nt_0*wd_nt_0)/Limm_nt_count_0)/norm_0;
    earn_NT_imm   = ((I_alt_nt  *wd_nt  )/Limm_nt_count  )/norm;
    earn_T_imm_ch  = earn_T_imm  / earn_T_imm_0  - 1;
    earn_NT_imm_ch = earn_NT_imm / earn_NT_imm_0 - 1;

    % --- Bundle as a 1-column table indexed by the row names this script reads ---
    names = { ...
        'earn_p'; 'prof_p'; 'income_real'; ...
        'emp_T'; 'emp_NT'; 'emp_eff_T'; 'emp_eff_NT'; ...
        'emp_nat_T'; 'emp_nat_NT'; 'emp_eff_nat_T'; 'emp_eff_nat_NT'; ...
        'emp_imm_T'; 'emp_imm_NT'; 'emp_eff_imm_T'; 'emp_eff_imm_NT'; ...
        'earn_T'; 'earn_NT'; 'w_T'; 'w_NT'; ...
        'earn_T_imm_ch'; 'earn_NT_imm_ch'; 'w_imm_T'; 'w_imm_NT'};
    vals = 100 * [ ...
        earn_p_ch; prof_p_ch; income_real_ch; ...
        emp_T_ch; emp_NT_ch; emp_eff_T_ch; emp_eff_NT_ch; ...
        emp_nat_T_ch; emp_nat_NT_ch; emp_eff_nat_T_ch; emp_eff_nat_NT_ch; ...
        emp_imm_T_ch; emp_imm_NT_ch; emp_eff_imm_T_ch; emp_eff_imm_NT_ch; ...
        earn_T_ch; earn_NT_ch; w_T_ch; w_NT_ch; ...
        earn_T_imm_ch; earn_NT_imm_ch; w_imm_T_ch; w_imm_NT_ch];
    T = table(vals, 'VariableNames', {'Change'}, 'RowNames', names);
end

